def load_csv(path: Path):
    rows = []
    with open(path, encoding="utf-8-sig") as f:
        reader = csv.DictReader(f)
        for r in reader:
            rows.append(r)
    return rows


def make_card(card_id: str, word: str, rank: int, freq: float, region: str = "") -> dict | None:
    if word in OCR_NOISE:
        return None
    if word not in TRANSLATIONS:
        return None  # 번역 없으면 skip (placeholder X)
    kana, back, key = TRANSLATIONS[word]
    full_key = f"{key} · #{rank} (freq {freq * 100:.2f}%)"
    card = {
        "id": card_id,
        "front": word,
        "kana": kana,
        "back": back,
        "key": full_key,
        "rank": rank,
    }
    if region:
        card["region"] = region
    return card


