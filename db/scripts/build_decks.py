def build_kanji_deck():
    data = json.loads((DB / "hanja_crossref.json").read_text(encoding="utf-8"))
    # 가중 빈도 분석 결과 로드
    weighted_csv = DB / "ja_kanji_weighted_freq.csv"
    weighted = {}  # kanji → (rank, weighted_pct, word_count)
    if weighted_csv.exists():
        import csv as _csv
        with open(weighted_csv, encoding="utf-8-sig") as f:
            for r in _csv.DictReader(f):
                weighted[r["kanji"]] = (
                    int(r["rank"]),
                    float(r["weighted_freq_pct"]),
                    int(r["word_count"]),
                )
    words_json = DB / "ja_kanji_words.json"
    examples = {}
    if words_json.exists():
        ex_data = json.loads(words_json.read_text(encoding="utf-8"))
        examples = ex_data.get("entries", {})

    cards = []
    for e in data["entries"]:
        rank = e.get("freq_rank") or 0
        ja = e["ja_kanji"]
        ko_hanja = e["ko_hanja"]
        ko_yumeum = e["ko_hanja_yumeum"]
        zh_simp = e["zh_simp"]
        zh_trad = e["zh_trad"]
        meaning = e["meaning_ko"]

        # cross-ref + 가중 빈도 + 예시 단어
        cross_parts = [f"ko: {ko_hanja}({ko_yumeum})"]
        if zh_simp != ja:
            cross_parts.append(f"zh-簡: {zh_simp}")
        if zh_trad != ja and zh_trad != zh_simp:
            cross_parts.append(f"zh-繁: {zh_trad}")
        key_parts = [" / ".join(cross_parts)]

        # 가중 빈도 정보
        wf = weighted.get(ja)
        if wf:
            wrank, wpct, wcount = wf
            key_parts.append(f"가중 빈도 #{wrank} ({wpct:.2f}%, {wcount}어 사용)")
        # 예시 단어 (top 3)
        exs = examples.get(ja, [])[:3]
        if exs:
            example_str = " · ".join(f"{w[0]}({w[2]})" for w in exs)
            key_parts.append(f"예: {example_str}")

        # readings (후리가나 list)
        readings = [
            {"reading": r, "kind": kind, "gloss": gloss}
            for r, kind, gloss in KANJI_READINGS.get(ja, [])
        ]
        # 대표 단어 3개 (한글 뜻 매핑 추가)
        ex_words = []
        for w in examples.get(ja, [])[:3]:
            word, freq, w_rank = w[0], w[1], w[2]
            entry = {"word": word, "freq": freq, "rank": w_rank}
            # 1) EXAMPLE_TRANSLATIONS 우선 (한자 분석 전용 확장 사전)
            # 2) TRANSLATIONS fallback (일반 사전)
            ko_back = None
            if word in EXAMPLE_TRANSLATIONS:
                ko_back = EXAMPLE_TRANSLATIONS[word]
            elif word in TRANSLATIONS:
                ko_back = TRANSLATIONS[word][1]
            if ko_back:
                entry["ko"] = ko_back
            ex_words.append(entry)
        cards.append({
            "id": e["id"].replace(":", "_"),
            "front": ja,
            "kana": "",
            "back": meaning,
            "key": " / ".join(key_parts),
            "ko_hanja": ko_hanja,
            "zh_simp": zh_simp,
            "zh_trad": zh_trad,
            "rank": rank,
            "weighted_rank": wf[0] if wf else None,
            "weighted_pct": wf[1] if wf else None,
            "readings": readings,
            "example_words": ex_words,
        })
    # 정렬: 가중 빈도 우선, 그 다음 freq_rank, 그 다음 미존재
    cards.sort(key=lambda c: (
        c["weighted_rank"] is None,
        c["weighted_rank"] or 9999,
    ))
    deck = {
        "deck_id": "kanji",
        "deck_name": "한자 코어 80",
        "deck_subtitle": f"4-way cross-ref (ja↔zh-簡↔zh-繁↔ko) — {len(cards)}자",
        "color": "0xFF6B6478",
        "icon": "漢",
        "unlock_threshold": 0,
        "source": "db/corpus/hanja_crossref.json",
        "cards": cards,
    }
    (APP_DATA / "deck_kanji.json").write_text(
        json.dumps(deck, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"  ✓ deck_kanji.json — {len(cards)} cards (hanja_crossref v4)")


def is_valid_jp(s: str) -> bool:
    """일본어 chars (hiragana, katakana, kanji) 포함 + 노이즈 제외."""
    if not s or len(s) > 30:
        return False
    if any(s.startswith(c) for c in "([<>~-)]"):
        return False
    if "Ⅱ" in s or "Ⅰ" in s or "일본어" in s:
        return False
    # 한글이 들어있으면 제외 (OCR 노이즈 — 페이지 머리/꼬리)
    if any("가" <= ch <= "힯" for ch in s):
        return False
    # 일본어 (히라가나/카타카나/한자) char 1개 이상 필요
    has_jp = any(
        ("぀" <= ch <= "ヿ") or  # hiragana + katakana
        ("一" <= ch <= "鿿") or  # CJK kanji
        ch == "～"
        for ch in s
    )
    return has_jp


def normalize_vocab_entry(raw: str) -> str | None:
    """'いえ' or 'あに ( 兄 )' → 'いえ' / 'あに'. 노이즈는 None."""
    import re
    s = raw.strip()
    if not is_valid_jp(s):
        return None
    # 한자 표기 부분 제거 — ( ... ) < ... > [ ... ] 그리고 / ~ 부분
    # 'あに ( 兄 )' → 'あに'
    s = re.split(r'\s*[(<\[/]', s, maxsplit=1)[0].strip()
    if not is_valid_jp(s):
        return None
    return s


def build_vocab_edu_deck():
    """한국 교육부 별책 II 기본 어휘 940 → 번역 가능한 어휘만."""
    path = DB / "edu" / "ja_vocab.json"
    if not path.exists():
        print(f"  · {path.name} 없음 — skip")
        return
    data = json.loads(path.read_text(encoding="utf-8"))
    raw_entries = data["entries"]
    # normalize + dedupe (순서 유지)
    seen = set()
    cleaned = []
    for raw in raw_entries:
        n = normalize_vocab_entry(raw)
        if n and n not in seen:
            seen.add(n)
            cleaned.append(n)

    cards = []
    skipped_no_trans = 0
    for i, word in enumerate(cleaned):
        if word in OCR_NOISE:
            continue
        if word not in TRANSLATIONS:
            skipped_no_trans += 1
            continue
        kana, back, key = TRANSLATIONS[word]
        cards.append({
            "id": f"edu_{i+1:03d}",
            "front": word,
            "kana": kana,
            "back": back,
            "key": f"{key} · 교육부 별책Ⅱ",
        })

    deck = {
        "deck_id": "vocab_edu",
        "deck_name": "교육부 기본 어휘",
        "deck_subtitle": f"한국 교육부 별책 Ⅱ 일본어 기본 어휘 ({len(cleaned)} 정제 어휘 중 번역 {len(cards)}장)",
        "color": "0xFF9DCEDB",
        "icon": "📘",
        "unlock_threshold": 0,
        "source": "db/corpus/edu/ja_vocab.json",
        "cards": cards,
    }
    (APP_DATA / "deck_vocab_edu.json").write_text(
        json.dumps(deck, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"  ✓ deck_vocab_edu.json — {len(cards)} cards (정제 {len(cleaned)}, 번역 사전 {skipped_no_trans} skip)")


def build_l1_turn_deck():
    """content/dialogues/L1.json → deck_l1_turn.json (이미 cycle 6 에 처리됐지만 확실히 재생성)."""
    l1_path = Path(__file__).resolve().parents[2] / "content" / "dialogues" / "L1.json"
    if not l1_path.exists():
        print(f"  · L1.json 없음 — skip")
        return
    l1 = json.loads(l1_path.read_text(encoding="utf-8"))
    cards = []
    for turn in l1.get("turns", []):
        num = turn["num"]
        cards.append({
            "id": f"l1_{num:03d}",
            "front": turn["ja"],
            "kana": turn.get("kana", ""),
            "back": turn["ko"],
            "key": turn.get("key", ""),
            "speaker": turn.get("speaker", ""),
            "ep": turn.get("ep", ""),
        })
    deck = {
        "deck_id": "l1_turn",
        "deck_name": "L1 회화 turn",
        "deck_subtitle": f"민준 × 사쿠라 narrative ({len(cards)} turn)",
        "color": "0xFFB8D2AE",
        "icon": "💬",
        "unlock_threshold": 0,
        "source": "content/dialogues/L1.json",
        "cards": cards,
    }
    (APP_DATA / "deck_l1_turn.json").write_text(
        json.dumps(deck, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"  ✓ deck_l1_turn.json — {len(cards)} cards")


